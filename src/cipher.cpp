inline std::uint64_t rotl64(std::uint64_t value, unsigned amount) {
	amount %= 64;
	return amount == 0 ? value : (value << amount) | (value >> (64 - amount));
}

inline Block128 rotl128(Block128 value, unsigned amount) {
	amount %= 128;
	if (amount == 0) {
		return value;
	}
	if (amount < 64) {
		return {
			(value.hi << amount) | (value.lo >> (64 - amount)),
			(value.lo << amount) | (value.hi >> (64 - amount))
		};
	}
	amount -= 64;
	return {
		(value.lo << amount) | (value.hi >> (64 - amount)),
		(value.hi << amount) | (value.lo >> (64 - amount))
	};
}

inline std::uint64_t subBytes(std::uint64_t x) {
	std::uint64_t out = 0;
	for (unsigned i = 0; i < 8; ++i) {
		std::uint64_t b = SBOX[(x >> (8 * i)) & 0xFF];
		out |= b << (8 * i);
	}
	return out;
}


inline std::uint64_t diffuse(std::uint64_t x) {
	return x ^ rotl64(x, 13) ^ rotl64(x, 28) ^ rotl64(x, 44);
}


inline std::array<RoundKey, ROUNDS> keySchedule(Block128 masterKey) {
	std::array<RoundKey, ROUNDS> rk{};
	Block128 k = masterKey;
	for (unsigned step = 0; step < ROUNDS; ++step) {
		k = rotl128(k, 13);
		k.hi ^= 0x9E3779B97F4A7C15ULL + step * 0x0101010101010101ULL;
		k.lo ^= 0xD1B54A32D192ED03ULL ^ (static_cast<std::uint64_t>(step) << 32);
		k.lo = subBytes(k.lo);
		rk[step] = {k.hi, k.lo};
	}
	return rk;
}

// Round function F(R, K):
//   1) t = R + K.a        (mod 2^64)
//   2) u = S(t)           (bytewise S-box)
//   3) w = u + K.b        (mod 2^64)
//   4) diffusion(w)
inline std::uint64_t roundFunction(std::uint64_t right, const RoundKey& key) {
	std::uint64_t t = right + key.a;
	std::uint64_t u = subBytes(t);
	std::uint64_t w = u + key.b;
	return diffuse(w);
}

inline Block128 feistel(Block128 input, const std::array<RoundKey, ROUNDS>& rk, bool decrypt) {
	std::uint64_t left = input.hi;
	std::uint64_t right = input.lo;
	for (int i = 0; i < ROUNDS; ++i) {
		const RoundKey& key = decrypt ? rk[ROUNDS - 1 - i] : rk[i];
		std::uint64_t next = left ^ roundFunction(right, key);
		left = right;
		right = next;
	}
	return {right, left}; 
}

inline Block128 encryptBlock(Block128 plaintext, Block128 masterKey) {
	return feistel(plaintext, keySchedule(masterKey), false);
}

inline Block128 decryptBlock(Block128 ciphertext, Block128 masterKey) {
	return feistel(ciphertext, keySchedule(masterKey), true);
}

inline unsigned hammingDistance(Block128 left, Block128 right) {
	return static_cast<unsigned>(__builtin_popcountll(left.hi ^ right.hi)
		+ __builtin_popcountll(left.lo ^ right.lo));
}

