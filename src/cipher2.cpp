inline std::uint64_t rotl64(std::uint64_t value, unsigned amount) {
	amount %= 64;
	return amount == 0 ? value : (value << amount) | (value >> (64 - amount));
}

inline std::uint64_t rotr64(std::uint64_t value, unsigned amount) {
	amount %= 64;
	return amount == 0 ? value : (value >> amount) | (value << (64 - amount));
}

inline Block128 rotl128(Block128 value, unsigned amount) {
	amount %= 128;
	if (amount == 0) return value;
	if (amount < 64) {
		return {
			(value.hi << amount) | (value.lo >> (64 - amount)),
			(value.lo << amount) | (value.hi >> (64 - amount))
		};
	}
	amount -= 64;
	return {
		(value.lo << amount) | (value.hi >> (64 - amount)),
		(value.hi << amount) | (value.lo >> (64 - amount))
	};
}

// 1. Substitusi Byte (Byte-level substitution)
inline Block128 substitute(Block128 value, const std::array<std::uint8_t, 256>& table) {
	Block128 result{0, 0};
	for (int i = 0; i < 8; ++i) {
		std::uint8_t byteHi = static_cast<std::uint8_t>((value.hi >> (56 - i * 8)) & 0xFF);
		std::uint8_t byteLo = static_cast<std::uint8_t>((value.lo >> (56 - i * 8)) & 0xFF);

		result.hi |= (static_cast<std::uint64_t>(table[byteHi]) << (56 - i * 8));
		result.lo |= (static_cast<std::uint64_t>(table[byteLo]) << (56 - i * 8));
	}
	return result;
}

// 2. Transposisi Byte (Permutation)
inline Block128 permuteBytes(Block128 value, const std::array<std::uint8_t, 16>& pbox) {
	std::array<std::uint8_t, 16> srcBytes;
	for (int i = 0; i < 8; ++i) {
		srcBytes[i] = static_cast<std::uint8_t>((value.hi >> (56 - i * 8)) & 0xFF);
		srcBytes[i + 8] = static_cast<std::uint8_t>((value.lo >> (56 - i * 8)) & 0xFF);
	}

	std::array<std::uint8_t, 16> dstBytes{};
	for (int i = 0; i < 16; ++i) {
		dstBytes[pbox[i]] = srcBytes[i];
	}

	Block128 result{0, 0};
	for (int i = 0; i < 8; ++i) {
		result.hi |= (static_cast<std::uint64_t>(dstBytes[i]) << (56 - i * 8));
		result.lo |= (static_cast<std::uint64_t>(dstBytes[i + 8]) << (56 - i * 8));
	}
	return result;
}

// 3. Mixing / Difusi Linear (ARX Layer)
inline void mix(Block128& state) {
	state.hi += rotl64(state.lo, 17);
	state.lo ^= rotl64(state.hi, 29);
	state.hi = rotl64(state.hi, 31);
}

inline void inverseMix(Block128& state) {
	state.hi = rotr64(state.hi, 31);
	state.lo ^= rotl64(state.hi, 29);
	state.hi -= rotl64(state.lo, 17);
}

// 4. Key Derivation Function (KDF / Key Schedule)
inline Block128 deriveRoundKey(Block128 masterKey, unsigned round) {
	Block128 roundKey = masterKey;
	for (unsigned step = 0; step <= round; ++step) {
		roundKey = rotl128(roundKey, 19 + step);
		roundKey.hi += (0x9E3779B97F4A7C15ULL ^ step);
		roundKey.lo ^= (0x243F6A8885A308D3ULL + (static_cast<std::uint64_t>(step) << 40));
	}
	return roundKey;
}

// 5. Endpoint Encrypt
inline Block128 encryptBlock(Block128 plaintext, Block128 masterKey) {
	Block128 state = plaintext;
	for (unsigned round = 0; round < ROUNDS; ++round) {
		Block128 rkey = deriveRoundKey(masterKey, round);
		
		// Key Addition (Penjumlahan Modulo 2^64 + XOR)
		state.hi += rkey.hi;
		state.lo ^= rkey.lo;

		// Byte Substitution
		state = substitute(state, SBOX);

		// Transposition / Permutation
		state = permuteBytes(state, P_BOX);

		// Linear Mixing (ARX)
		mix(state);
	}
	
	// Final Key Addition Layer
	Block128 finalKey = deriveRoundKey(masterKey, ROUNDS);
	state.hi += finalKey.hi;
	state.lo ^= finalKey.lo;

	return state;
}

// 6. Endpoint Decrypt
inline Block128 decryptBlock(Block128 ciphertext, Block128 masterKey) {
	Block128 state = ciphertext;

	// Reverse Final Key Addition Layer
	Block128 finalKey = deriveRoundKey(masterKey, ROUNDS);
	state.hi -= finalKey.hi;
	state.lo ^= finalKey.lo;

	for (int round = ROUNDS - 1; round >= 0; --round) {
		Block128 rkey = deriveRoundKey(masterKey, static_cast<unsigned>(round));

		// Inverse Linear Mixing
		inverseMix(state);

		// Inverse Transposition / Permutation
		state = permuteBytes(state, INV_P_BOX);

		// Inverse Byte Substitution
		state = substitute(state, INV_SBOX);

		// Reverse Key Addition
		state.hi -= rkey.hi;
		state.lo ^= rkey.lo;
	}

	return state;
}

inline unsigned hammingDistance(Block128 left, Block128 right) {
	return static_cast<unsigned>(__builtin_popcountll(left.hi ^ right.hi)
		+ __builtin_popcountll(left.lo ^ right.lo));
}

